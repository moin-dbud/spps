import { useState, useRef, useEffect, useCallback, type ChangeEvent } from "react";
import { Sparkles, RefreshCw, Check, Loader2 } from "lucide-react";
import { apiTranslate } from "../../utils/api";
import "./MultilingualField.css";

export type SupportedLanguage = "en" | "mr" | "hi";

export interface MultilingualValues {
  en: string;
  mr: string;
  hi: string;
}

export interface MultilingualFieldProps {
  label: string;
  values: MultilingualValues;
  onChange: (updated: MultilingualValues) => void;
  required?: boolean;
  type?: "input" | "textarea";
  rows?: number;
  placeholder?: {
    en?: string;
    mr?: string;
    hi?: string;
  };
  context?: "name" | "title" | "general" | "content";
  className?: string;
  helperText?: string;
}

export default function MultilingualField({
  label,
  values,
  onChange,
  required = false,
  type = "input",
  rows = 3,
  placeholder,
  context = "general",
  className = "",
  helperText,
}: MultilingualFieldProps) {
  const [translating, setTranslating] = useState(false);
  const [lastAutoSource, setLastAutoSource] = useState<SupportedLanguage | null>(null);

  // Track which fields were manually edited by the user
  const [manuallyEdited, setManuallyEdited] = useState<{
    en: boolean;
    mr: boolean;
    hi: boolean;
  }>({
    en: false,
    mr: false,
    hi: false,
  });

  // Track which fields were auto-populated
  const [autoGenerated, setAutoGenerated] = useState<{
    en: boolean;
    mr: boolean;
    hi: boolean;
  }>({
    en: false,
    mr: false,
    hi: false,
  });

  // Keep a ref to latest values to avoid stale closures in debounced calls
  const valuesRef = useRef(values);
  valuesRef.current = values;

  const manuallyEditedRef = useRef(manuallyEdited);
  manuallyEditedRef.current = manuallyEdited;

  const reqIdRef = useRef(0);
  const debounceTimerRef = useRef<any>(null);

  // Perform translation from a given source language
  const triggerAutoTranslation = useCallback(
    async (sourceLang: SupportedLanguage, text: string, forceAll = false) => {
      const cleanText = text.trim();
      if (!cleanText) return;

      const currentReqId = ++reqIdRef.current;
      setTranslating(true);

      const targetLangs: SupportedLanguage[] = (["en", "mr", "hi"] as SupportedLanguage[]).filter(
        (lang) => lang !== sourceLang
      );

      // Determine which target fields can be auto-populated:
      // If forceAll is true, translate all targets.
      // Otherwise, only translate targets that haven't been manually edited by the user.
      const eligibleTargets = forceAll
        ? targetLangs
        : targetLangs.filter((lang) => !manuallyEditedRef.current[lang]);

      if (eligibleTargets.length === 0) {
        setTranslating(false);
        return;
      }

      try {
        const res = await apiTranslate({
          text: cleanText,
          sourceLang,
          targetLangs: eligibleTargets,
          context,
        });

        // Discard out-of-order responses
        if (currentReqId !== reqIdRef.current) return;

        if (res.success && res.translations) {
          const nextValues: MultilingualValues = { ...valuesRef.current };
          const nextAutoGenerated = { ...autoGenerated };

          for (const target of eligibleTargets) {
            const translated = res.translations[target];
            if (translated) {
              nextValues[target] = translated;
              nextAutoGenerated[target] = true;
            }
          }

          setLastAutoSource(sourceLang);
          setAutoGenerated(nextAutoGenerated);
          onChange(nextValues);
        }
      } catch (err) {
        console.warn("[MultilingualField] Translation error:", err);
      } finally {
        if (currentReqId === reqIdRef.current) {
          setTranslating(false);
        }
      }
    },
    [autoGenerated, context, onChange]
  );

  // Handle typing in any of the 3 fields
  const handleFieldChange = (lang: SupportedLanguage, newText: string) => {
    // 1. Immediately update local field value
    const nextValues: MultilingualValues = {
      ...values,
      [lang]: newText,
    };
    onChange(nextValues);

    // 2. Mark this language field as user-edited (not auto-generated)
    setManuallyEdited((prev) => ({ ...prev, [lang]: true }));
    setAutoGenerated((prev) => ({ ...prev, [lang]: false }));

    // 3. Clear pending debounce timer
    if (debounceTimerRef.current) {
      clearTimeout(debounceTimerRef.current);
    }

    // If text was cleared, do not translate
    if (!newText.trim()) return;

    // 4. Debounce translation request by 600ms
    debounceTimerRef.current = setTimeout(() => {
      triggerAutoTranslation(lang, newText, false);
    }, 600);
  };

  // Explicit user action: "Translate again"
  const handleForceRetranslate = () => {
    // Pick the most complete source language
    let bestSource: SupportedLanguage = "en";
    if (values.en.trim()) {
      bestSource = "en";
    } else if (values.mr.trim()) {
      bestSource = "mr";
    } else if (values.hi.trim()) {
      bestSource = "hi";
    }

    const sourceText = values[bestSource].trim();
    if (!sourceText) return;

    triggerAutoTranslation(bestSource, sourceText, true);
  };

  // Cleanup timers on unmount
  useEffect(() => {
    return () => {
      if (debounceTimerRef.current) clearTimeout(debounceTimerRef.current);
    };
  }, []);

  const hasAnyContent = Boolean(values.en.trim() || values.mr.trim() || values.hi.trim());

  return (
    <div className={`ml-field ${className}`}>
      <div className="ml-field__header">
        <div className="ml-field__label-wrap">
          <label className="ml-field__label">
            {label}
            {required && <span className="ml-field__required">*</span>}
          </label>
          <span className="ml-field__badge">
            <Sparkles size={11} /> Auto-Translation Active{lastAutoSource ? ` (${lastAutoSource.toUpperCase()} detected)` : ""}
          </span>
        </div>

        <div className="ml-field__actions">
          {translating && (
            <span className="ml-field__status">
              <Loader2 size={13} className="ml-field__spinner" />
              <span>Translating...</span>
            </span>
          )}

          {hasAnyContent && (
            <button
              type="button"
              className="ml-field__retranslate-btn"
              onClick={handleForceRetranslate}
              disabled={translating}
              title="Force re-translation from current content"
            >
              <RefreshCw size={11} className={translating ? "ml-field__spinner" : ""} />
              <span>Translate Again</span>
            </button>
          )}
        </div>
      </div>

      <div className="ml-field__grid">
        {/* 1. English (EN) */}
        <div className="ml-field__column">
          <div className="ml-field__lang-tag">
            <span className="ml-field__tag-pill ml-field__tag-pill--en">EN</span>
            <span>English</span>
            {autoGenerated.en && (
              <span className="ml-field__state-indicator ml-field__state-indicator--auto" title="Auto-translated">
                <Check size={10} /> Auto
              </span>
            )}
            {manuallyEdited.en && (
              <span className="ml-field__state-indicator ml-field__state-indicator--manual" title="Edited manually">
                Manual
              </span>
            )}
          </div>
          <div className="ml-field__input-wrap">
            {type === "textarea" ? (
              <textarea
                className="ml-field__input ml-field__textarea"
                rows={rows}
                placeholder={placeholder?.en || `Enter in English...`}
                value={values.en}
                onChange={(e: ChangeEvent<HTMLTextAreaElement>) => handleFieldChange("en", e.target.value)}
                required={required}
              />
            ) : (
              <input
                type="text"
                className="ml-field__input"
                placeholder={placeholder?.en || `Enter in English...`}
                value={values.en}
                onChange={(e: ChangeEvent<HTMLInputElement>) => handleFieldChange("en", e.target.value)}
                required={required}
              />
            )}
          </div>
        </div>

        {/* 2. Marathi (मराठी) */}
        <div className="ml-field__column">
          <div className="ml-field__lang-tag">
            <span className="ml-field__tag-pill ml-field__tag-pill--mr">मराठी</span>
            <span>Marathi</span>
            {autoGenerated.mr && (
              <span className="ml-field__state-indicator ml-field__state-indicator--auto" title="Auto-translated">
                <Check size={10} /> Auto
              </span>
            )}
            {manuallyEdited.mr && (
              <span className="ml-field__state-indicator ml-field__state-indicator--manual" title="Edited manually">
                Manual
              </span>
            )}
          </div>
          <div className="ml-field__input-wrap">
            {type === "textarea" ? (
              <textarea
                className="ml-field__input ml-field__textarea"
                rows={rows}
                placeholder={placeholder?.mr || `मराठीत प्रविष्ट करा...`}
                value={values.mr}
                onChange={(e: ChangeEvent<HTMLTextAreaElement>) => handleFieldChange("mr", e.target.value)}
              />
            ) : (
              <input
                type="text"
                className="ml-field__input"
                placeholder={placeholder?.mr || `मराठीत प्रविष्ट करा...`}
                value={values.mr}
                onChange={(e: ChangeEvent<HTMLInputElement>) => handleFieldChange("mr", e.target.value)}
              />
            )}
          </div>
        </div>

        {/* 3. Hindi (हिंदी) */}
        <div className="ml-field__column">
          <div className="ml-field__lang-tag">
            <span className="ml-field__tag-pill ml-field__tag-pill--hi">हिंदी</span>
            <span>Hindi</span>
            {autoGenerated.hi && (
              <span className="ml-field__state-indicator ml-field__state-indicator--auto" title="Auto-translated">
                <Check size={10} /> Auto
              </span>
            )}
            {manuallyEdited.hi && (
              <span className="ml-field__state-indicator ml-field__state-indicator--manual" title="Edited manually">
                Manual
              </span>
            )}
          </div>
          <div className="ml-field__input-wrap">
            {type === "textarea" ? (
              <textarea
                className="ml-field__input ml-field__textarea"
                rows={rows}
                placeholder={placeholder?.hi || `हिन्दी में दर्ज करें...`}
                value={values.hi}
                onChange={(e: ChangeEvent<HTMLTextAreaElement>) => handleFieldChange("hi", e.target.value)}
              />
            ) : (
              <input
                type="text"
                className="ml-field__input"
                placeholder={placeholder?.hi || `हिन्दी में दर्ज करें...`}
                value={values.hi}
                onChange={(e: ChangeEvent<HTMLInputElement>) => handleFieldChange("hi", e.target.value)}
              />
            )}
          </div>
        </div>
      </div>

      {helperText && <span className="ml-field__helper">{helperText}</span>}
    </div>
  );
}

